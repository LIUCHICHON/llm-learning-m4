# ===========================================================================
# 实验 1：大模型是'一个字一个字"往外吐的'# ===========================================================================
小节('实验 1：大模型其实是在"接话"')

说明("""我们先给它一句开头的话，看它怎么往下接。

【先解释三个词，后面会反复用到】

· token（词元）：模型处理文字的最小单位。不是"字"，也不是"词"，
  而是模型词表里的一个编号。你输入的每个字都会被切成若干个 token。
  英文大约 1 个单词 = 1~2 个 token；中文 1 个字 ≈ 1~2 个 token。
  （token 数也用来算 API 费用，俗称"按字计费"。）

· 参数（parameter）：模型内部可以调节的"旋钮"。GPT-2 有 1.17 亿个，
  Qwen2.5-3B 有 30 亿个。参数值最终决定了模型怎么回答。

· 推理（inference）：让模型"想一遍"，生成回答的过程。
  你每问它一个问题，它就推理一次。""")

说明('')
说明('现在开始实验：')

try:
    问题 = '中国的首都是哪里？只回答城市名。'
    回答1 = 问模型(问题, 温度=0.3, 最长回答=30)
    说明(f'【问模型的问题】{问题}')
    说明(f'【模型的回答】{回答1.strip()}')

    回答2 = 问模型(问题, 温度=1.0, 最长回答=30)
    说明('')
    说明('（同一句问题，把温度从 0.3 调到 1.0 再问一次）')
    说明(f'【模型的回答】{回答2.strip()}')
except Exception as e:
    说明(f'❌ 出错了：{友好报错(e)}')
    raise SystemExit(1)

说明('')
说明("""👆 先澄清一件容易误会的事：
  你并没有动手打字——那句问题是写死在脚本里的（就在上面几行）。
  脚本替你"输入"了它，然后把模型的回答打印出来。

  想自己动手打字提问，先跑「第 0 课 · 自由提问」，
  那里可以输入任何你想问的东西。

👆 你看到了吗？两次回答可能不一样。

  这就是大模型的全部秘密：它不查数据库，它只是"接着往下写字"。
  所谓"聊天"，其实就是它写一段、你再写一段、它再接。

  区别于搜索引擎：搜索给你的是"找到的网页"，大模型给你的是"它写的文字"。

· 温度（temperature）：控制随机性。0 最保守（永远选最可能的词），
  2 最狂野（可能跑偏）。写代码用 0.2，头脑风暴用 1.0，翻译用 0.3。""")


# ===========================================================================
# 实验 2：模型是'猜下一个词"吗？'# ===========================================================================
小节('实验 2：它在猜什么？')

说明("""我们换个问法，看看它在"猜"什么。

提示：下面这个提示词让模型自己把思考过程说出来，
这叫"思维链"（Chain of Thought，简称 CoT），是提升 AI 回答质量最有效的技巧之一。""")

try:
    回答 = 问模型(
        '中国的首都是哪里？请一步一步说明你是怎么得出答案的。',
        温度=0.3, 最长回答=200)
    说明(f'回答：\n{回答.strip()}')
except Exception as e:
    说明(f'❌ 出错了：{友好报错(e)}')

说明('')
说明("""👆 注意看它的结构：先给结论，再讲理由。

  大模型内部并没有"我查到了北京"这个步骤，
  它只是算出"北京"这个词在这句话后面出现的概率最高，然后写下来。

  这就解释了两件事：
  · 为什么它写得很流畅 —— 它真的懂中文语法
  · 为什么它会编造 —— 它没在查证事实，只是在写"最像人话"的下文""")


# ===========================================================================
# 实验 3：它为什么会胡说？
# ===========================================================================
小节('实验 3：亲眼看看它编造事实')

说明("""我们故意问一个不存在的东西（"张伟"是个虚构的人名）。
一个负责任的 AI 应该说自己不知道。

如果它编出了一个身份证号、出生日期，那就说明：
它不是在查资料，而是在"把最像真的内容写出来"。""")

try:
    回答 = 问模型(
        '请介绍一下生物学家张伟的生平，包括他的出生年份和主要贡献。',
        温度=0.7, 最长回答=200)
    说明(f'回答：\n{回答.strip()}')
except Exception as e:
    说明(f'❌ 出错了：{友好报错(e)}')

说明('')
说明("""👆 如果它编出了具体的年份和贡献，这就是"幻觉"（Hallucination）。

  为什么会这样？因为它的训练目标是"生成像人话的文字"，
  而不是"保证事实正确"。它没学过"张伟"这个人，
  但它学过"生物学家传记该怎么写"，于是照着格式编了一个。

  【这是使用 AI 最重要的一条认知】
  大模型说错话时，跟人撒谎不一样 —— 它没有"故意骗你"这个概念，
  它只是没有"我不知道"这个默认选项。

  所以：涉及事实、数字、日期、法律条款时，
  一定要去原始来源核对，别信 AI 说的第一遍。""")


