小节('第 4 部分：AI 内容标识的几种办法')

说明('''水印只是其中一种办法。整个领域有几种思路：

【1. 隐形水印（本课学的）】
  嵌入统计规律，检测需要知道算法。
  优点：文本看起来完全自然。缺点：改写/翻译会破坏。

【2. 元数据标记】
  在文件里塞隐藏信息（比如 PNG 里有 C2PA 标记）。
  优点：稳，不会被破坏。缺点：转格式就没了。

【3. 官方标识 / 披露要求】
  中国《生成式人工智能服务管理暂行办法》要求：
  提供生成式 AI 服务时，要标识生成内容。
  欧盟 AI 法案也有类似要求。
  优点：法律层面强制。缺点：依赖自觉和平台执行。

【4. 检测器（反向思路）】
  不加戳，而是训练一个"AI 文本检测器"，
  看文本像不像 AI 写的。
  缺点：误判率高（人写的正式文件也可能被判成 AI），
        而且现在已有方法专门绕过检测器。

【现状】
  目前没有"绝对可靠"的单一方案，行业共识是组合使用：
  内容水印 + 元数据 + 平台披露 + 人工复核。''')


