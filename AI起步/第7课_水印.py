小节('第 2 部分：动手——生成一段带水印的文字')

XSIR目录 = os.path.expanduser('~/llm-lab/X-SIR')

if not os.path.exists(XSIR目录):
    说明(f'❌ 没找到 X-SIR：{XSIR目录}')
    说明('   请先运行：bash 安装环境.sh')
else:
    sys.path.insert(0, XSIR目录)
    os.chdir(XSIR目录)

    try:
        import torch
        from transformers import (AutoTokenizer, AutoModelForCausalLM,
                                  LogitsProcessorList)
        from src_watermark.kgw.extended_watermark_processor import (
            WatermarkLogitsProcessor as KGW,
            WatermarkDetector,
        )

        说明('① 加载小模型 GPT-2（够用了，原理一样）...')
        tok = AutoTokenizer.from_pretrained('gpt2')
        tok.pad_token = tok.eos_token
        模型 = AutoModelForCausalLM.from_pretrained('gpt2').to('mps')
        模型.eval()
        词表 = list(tok.get_vocab().values())
        print('   ✅ 模型就绪', flush=True)

        def 造水印器(强度):
            '''创建水印处理器。强度=绿名单占比，0.5 表示一半的词在绿名单。'''
            return KGW(vocab=词表, gamma=强度, delta=2.0,
                       seeding_scheme='simple_1')

        def 生成(提示词列表, 水印器):
            '''用指定的水印器生成文本。'''
            结果 = []
            for 提示 in 提示词列表:
                ids = tok(提示, return_tensors='pt').to('mps')
                with torch.no_grad():
                    out = 模型.generate(
                        **ids, max_new_tokens=90, do_sample=True,
                        logits_processor=LogitsProcessorList([水印器]),
                        temperature=1.0, top_k=0,
                        pad_token_id=tok.eos_token_id)
                结果.append(tok.decode(out[0][ids['input_ids'].shape[1]:],
                                       skip_special_tokens=True))
            return 结果

        提示词列表 = [
            'The capital of France is',
            'Water boils at a temperature of',
        ]

        说明('')
        说明('② 生成【不带水印】的文本（强度设为 0，等于没加水印）...')
        无水印文本 = 生成(提示词列表, 造水印器(0.0))
        for 提示, 文本 in zip(提示词列表, 无水印文本):
            print(f'   「{提示}」')
            print(f'      → {文本.strip()[:90]}')

        说明('')
        说明('③ 生成【带水印】的文本（强度 0.5）...')
        有水印文本 = 生成(提示词列表, 造水印器(0.5))
        for 提示, 文本 in zip(提示词列表, 有水印文本):
            print(f'   「{提示}」')
            print(f'      → {文本.strip()[:90]}')

        # ---------------- 检测 ----------------
        说明('')
        说明('④ 用检测器给两段文本打分')
        检测器 = WatermarkDetector(
            device=torch.device('mps'), tokenizer=tok, vocab=词表,
            gamma=0.5, delta=2.0, seeding_scheme='simple_1',
            z_threshold=4.0, normalizers=[], ignore_repeated_ngrams=True)

        def 算z(文本):
            r = 检测器.detect(text=文本)
            if isinstance(r, dict):
                return r.get('z_score', 0.0)
            return r

        print()
        print(f'   {"提示":<32}{"无水印z":>10}{"有水印z":>10}   判定')
        print('   ' + '-' * 62)
        for i, 提示 in enumerate(提示词列表):
            z1 = 算z(无水印文本[i])
            z2 = 算z(有水印文本[i])
            判定 = '✅ 检出' if z2 > 4.0 else '⚠️ 未达阈值'
            print(f'   {提示[:30]:<32}{z1:>10.3f}{z2:>10.3f}   {判定}')

        说明('')
        说明('''👆 这就是水印的全部魔法。

  看第一列：无水印的 z-score 在 0 附近随机波动
  看第二列：带水印的 z-score 明显更高（通常 > 4）

  【关键点】
  · 两段文字读起来一样自然，人眼看不出区别
  · 但检测器用"绿名单"这个隐藏规则一扫，分数立刻分开

  【实战意义】
  · 平台可以给 AI 生成的内容加戳，然后自动检测
  · 前提是：检测方知道用的是哪种水印算法和参数
    （所以工业界在推动"水印标准化"）

  【水印的弱点——也很重要】
  1. 文本被改写（paraphrase）后，水印会减弱
  2. 文本被翻译后，水印基本失效
  3. 文本太短时，统计量不足，检测不准（所以要长文本）
  4. 有人专门研究"洗掉水印"的方法

  所以水印是"提高造假成本"的手段，不是"绝对保证"。''')

    except Exception as e:
        说明('')
        说明(f'❌ 出错了：{友好报错(e)}')


