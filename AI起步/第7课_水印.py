标题('第 7 课 · 给 AI 生成的内容盖个戳（水印）')

说明('''## 为什么需要水印

想象这些场景：
  · 老师要判断作业是不是 AI 写的
  · 平台要标注"本文由 AI 生成"
  · 有人拿 AI 洗稿冒充原创
  · 你自己想让读者知道这段文字来自 AI

水印（watermark）的思路：在生成内容时，
悄悄按某种规则"标记"每一个词。肉眼看不出来，
但用同一套规则就能检测出来。

【和"隐形墨水"的区别】
  传统隐形墨水是物理标记；AI 水印是"统计规律"——
  文字的用词分布带上了模型的指纹。''')


# ===========================================================================
# 第 1 部分：核心原理
# ===========================================================================
小节('第 1 部分：核心原理 —— 绿名单')

说明('''【思路：让模型"偏心"】

模型生成下一个词时，会给词表里每个词打概率分，然后按概率抽一个。

水印算法做的事：
  1. 把词表分成两半：一半叫"绿名单"，一半叫"红名单"
     （分法由当前上下文的哈希决定，所以外人猜不到）
  2. 如果这一轮要写"1"，就给绿名单的词加分
     如果要写"0"，就给红名单的词加分
  3. 结果：带水印的文字里，"绿词"出现的比例会异常偏高

【检测：看比例偏了多少】
  如果水印强度是 50%（一半词在绿名单），
  那么正常文本里绿词占比应该在 50% 附近随机波动。
  统计足够多的词，就能看出它是否系统性偏高。

  这个偏差用 z-score（z 分数）表示：
    z-score = 0  → 跟随机没区别（没水印）
    z-score > 4  → 高度确信有水印

【为什么它能藏住】
  因为偏移只是"稍微"提高了一点点概率，
  文本读起来依然完全自然。''')


