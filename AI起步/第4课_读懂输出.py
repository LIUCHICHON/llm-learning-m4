# 1. token 与计费
# ===========================================================================
小节('第 1 部分：一个字到底值多少钱')

说明('''【token 是什么】
  模型处理文字的最小单位。你输入的每个字都会被切成若干 token，
  每个 token 在模型内部是一个编号。

【为什么要关心】
  1. 所有大模型 API 都按 token 计费（输入算钱，输出也算钱，通常输出更贵）
  2. token 数有上限，超了就报错
  3. 同样的意思，不同写法 token 数差很多

【怎么估算（心算用，精确值看下面实测）】
  中文：1 个汉字大约 0.5~1 个 token
  英文：1 个单词大约 1~1.5 个 token
  数字和标点：常常一个字符就占一个 token

下面这张表，是用你本机的 Ollama 真实测出来的。
测法说清楚，你才信得过这些数字：
  · 测什么：5 段文字，各自有多少个字符、被切成多少个 token
  · 用什么测：本机 Ollama 引擎 + qwen2.5:0.5b 模型的分词器
  · 怎么测：把文字原样送给 Ollama 切分（raw 模式，不套聊天模板，
    也只让它生成 1 个 token 就停），读它返回的 token 个数。
    这就是模型真正"看到"的 token 数，不是估算。

【实测结果表】（token 数用上面的方法真实测出，不是估算）

| 样例 | 字符数 | token 数 | 每 token 装几个字符 |
|------|--------|----------|---------------------|
| 短句子 | 2 | 1 | 2.00 |
| 一句话 | 8 | 4 | 2.00 |
| 一段话 | 43 | 22 | 1.95 |
| 英文 | 44 | 10 | 4.40 |
| 数字和符号 | 35 | 30 | 1.17 |''')

try:
    from AI工具箱 import 数token

    样例 = [
        ('短句子', '你好'),
        ('一句话', '今天天气怎么样？'),
        ('一段话', '人工智能正在深刻改变软件开发的方式，代码生成、测试、部署等环节都能得到 AI 的辅助。'),
        ('英文', 'The quick brown fox jumps over the lazy dog.'),
        ('数字和符号', '2026年3月15日，A/B测试通过率98.6%，费用¥1234.56'),
    ]
    说明('')
    说明('【现场实测】你自己跑一遍，数字应该和上面那张表一致：')
    说明(f'{"样例":<12}{"字符数":>8}{"token数":>9}   每token装')
    说明('-' * 58)
    for 名称, 文本 in 样例:
        n = 数token(文本)
        比 = f'{len(文本)/n:.2f} 字/token'
        说明(f'{名称:<12}{len(文本):>8}{n:>9}   {比}')
except Exception as e:
    说明('（跳过分词器实验：' + 友好报错(e) + '）')

说明('')
说明('''👆 注意看这张表，它和很多人的直觉相反：
  · 英文反而最省：那句 9 个英文单词的话（The quick brown fox jumps over
    the lazy dog.）只用了 10 个 token，平均一个 token 装 4.4 个字符
  · 中文居中：一个汉字大约只占半个 token（表里 2 个字符才用 1 个 token），
    并不是"一个字要一两个 token"
  · 数字和标点最"贵"：那段混着日期、百分号和 ¥ 符号的文字，
    35 个字符用了 30 个 token，几乎一个字符一个 token

  所以"用中文写提示词更省钱"是误解。真正省钱的做法是删废话。

【省钱小技巧】
  1. 删掉没用的废话（"请帮我""谢谢""我想了解一下"这些都占 token）
  2. 长的参考资料不要每次重发，让它先总结一次再问
  3. 简单任务用小模型，复杂任务才上大模型''')


