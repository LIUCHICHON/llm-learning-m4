小节('第 4 部分：这一课的术语速查表')

说明('''【token / 词元】
  模型处理文字的最小单位。所有 API 按它计费。
  中文 1 字 ≈ 0.5~1 token，英文 1 词 ≈ 1~1.5 token（以本机实测为准）。

【上下文窗口 / context window】
  模型一次能"看到"的文字总量上限。超了就报错或静默截断。

【logits】
  模型给每个候选词打的原始分数。可以是负数，是概率取对数后的值。

【softmax】
  把一堆分数变成概率的一步操作，让所有概率加起来等于 1。

【温度 / temperature】
  调节概率分布陡峭程度。低温保守，高温奔放。

【参数 / parameter】
  模型内部可调节的"旋钮"。3B 表示 30 亿个。
  参数越多，一般能力越强，但需要的内存也越多。

【推理 / inference】
  让模型"想一遍"生成回答。你每问一次就是一次推理。

【微调 / fine-tuning】
  用你自己的数据继续训练已有的模型，让它更懂你的领域。
  下一课会亲手做。

【量化 / quantization】
  把模型权重从 16 位压到 4 位或 8 位，省内存，代价是精度略降。
  （你在 Ollama 里用的模型基本都是量化版）''')


