# 2. 上下文窗口
# ===========================================================================
小节('第 2 部分：模型能一次看多少东西')

说明('''【上下文窗口（context window）】
  模型一次能"看到"的文字总量上限。包括：
    你的系统提示 + 你的问题 + 模型的回答 + 历史对话记录

【超了会怎样】
  · 报错（"context length exceeded"）
  · 或者：开头的内容被悄悄丢掉（更危险，你可能不知道）

【各模型大概多大】
  · qwen2.5:3b      ≈ 32K token
  · qwen3-8b        ≈ 32K token
  · 网上大模型      常见 128K ~ 200K token

【一个反直觉的事实】
  塞更多资料 ≠ 效果更好。资料太多时，
  模型会"抓不住重点"（这叫 lost in the middle 现象）。

  实测建议：一次给 3~5 段最相关的材料，比给 50 段效果更好。''')

长材料 = ('人工智能技术正在快速发展。' * 200)

说明("""【两轮实验的提问】
  第一次：把「这篇文章讲了什么？」加上 200 句重复材料一起问它。
  第二次：同样这堆材料，但前面加一句「提取要点后回答」，后面加「请用一句话总结」。""")

try:
    短问 = '这篇文章讲了什么？'
    回答 = 问模型(短问 + '\\n\\n' + 长材料, 温度=0.3, 最长回答=120)
    说明('【塞进 200 句重复材料后问"讲了什么"】')
    说明('   ' + 回答.strip().replace('\n', '\\n   ')[:250])
except Exception as e:
    说明('❌ ' + 友好报错(e))

说明('')
try:
    回答 = 问模型('提取要点后回答：\\n\\n' + 长材料 + '\\n\\n请用一句话总结。',
                  温度=0.3, 最长回答=100)
    说明('【同样的材料，但先让它"提取要点"】')
    说明('   ' + 回答.strip().replace('\n', '\\n   ')[:250])
except Exception as e:
    说明('❌ ' + 友好报错(e))

说明('')
说明('👆 第二个回答更聚焦。**给资料的方式**和**给多少资料**，同样重要。')


