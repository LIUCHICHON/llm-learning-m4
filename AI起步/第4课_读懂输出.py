# 3. logits 与概率
# ===========================================================================
小节('第 3 部分：模型内部的"打分"')

说明('''【logits 是什么】
  模型每生成一个词之前，会先给词表里 EVERY 一个词打一个分（原始分数），
  这个分数数组就叫 logits。

【它怎么变成最终输出】
  1. 模型算出每个词的 logits（原始分，可能正可能负）
  2. 变成概率：除以一个总和，让所有词的概率加起来 = 1
  3. 温度调节这个分布的"陡峭程度"：
     · 温度低 → 概率分布变尖，最高分的词几乎必选
     · 温度高 → 分布变平，冷门词也有机会被选中
  4. 按概率随机抽一个词（这就是 do_sample=True）

【看一个真实例子】
  我们让模型接着写"中国的首都是"，看看它给"北京"打了多少分。
  说明一下：这里没有走 Ollama，而是直接把 0.5B 模型加载进 Python。
  原因是 Ollama 的接口只给你最终回答，不给你"每个词的原始分数"；
  要看 logits，就得直接跟模型对话。数据同样真实，只是换了个测法。''')

try:
    import torch
    from transformers import AutoTokenizer, AutoModelForCausalLM

    tok = AutoTokenizer.from_pretrained('Qwen/Qwen2.5-0.5B-Instruct')
    model = AutoModelForCausalLM.from_pretrained('Qwen/Qwen2.5-0.5B-Instruct')
    model.eval()

    输入 = '中国的首都是'
    ids = tok(输入, return_tensors='pt')['input_ids']

    with torch.no_grad():
        logits = model(ids).logits[0, -1]

    # 变成概率
    概率 = torch.softmax(logits, dim=-1)

    top5 = torch.topk(概率, 5)
    说明('')
    说明(f'模型接着写「{输入}」时，最看好的 5 个词：')
    说明('')
    说明(f'{"候选词":<14}{"概率":>10}{"logits":>12}')
    说明('-' * 40)
    for p, l, idx in zip(top5.values, top5.indices, top5.indices):
        词 = tok.decode([idx])
        说明(f'{词:<14}{float(p)*100:>9.2f}%{float(logits[idx]):>12.2f}')

    说明('')
    说明('【怎么读这张表】')
    说明('  · 第一列：模型认为最可能接在后面的词')
    说明('  · 概率列：如果是 60%，说明模型有六成把握选它')
    说明('  · logits 列：原始分数，可以是负数。它其实是概率的对数（log）')
    说明('  · 把 logits 变概率的那一步，就叫 softmax')

    # 演示温度对概率分布的影响
    说明('')
    说明('【温度如何改变分布】—— 同一个词，在不同温度下的概率：')
    说明('')
    说明(f'{"温度":>8}{"第一名概率":>14}{"解释":>24}')
    说明('-' * 48)
    for T in [0.1, 0.7, 1.5]:
        调整后 = torch.softmax(logits / T, dim=-1)
        最高 = float(torch.max(调整后)) * 100
        解释 = {0.1: '几乎必选最可能词', 0.7: '平衡，最常用', 1.5: '冷门词也有机会'}[T]
        说明(f'{T:>8}{最高:>13.2f}%{解释:>22}')
except Exception as e:
    说明('（跳过内部机制实验：' + 友好报错(e) + '）')

说明('')
说明('''👆 温度越高，概率分布越平，"第一名"的优势越小。

【实用对照表】
  写代码、算数、翻译  → 温度 0.1 ~ 0.3
  日常问答、写作     → 温度 0.6 ~ 0.8
  头脑风暴、起名     → 温度 0.9 ~ 1.2
  绝对不要超过 1.5   → 会开始胡言乱语''')


