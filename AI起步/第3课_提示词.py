# 实验 3：把 AI 掰回来
# ===========================================================================
小节('实验 3：AI 写错了怎么办')

说明('''实战中，AI 第一次写的东西很少直接能用。关键是"怎么改"。

【三种改法，从好到差】

  改法 1（最好）：指出具体问题 + 说清你要什么
      "第 2 条太笼统了，请具体说明是哪个配置文件、是哪个字符"

  改法 2（可用）：给它一个反例
      "不对，我要的是这种：xxx。你再写一版。"

  改法 3（最差）："不对，重来" + 不说哪里不对
      模型会乱猜，可能离原问题越来越远。

我们看个实际对比。''')

第一版要求 = '''帮我写一条给客户的产品延期通知短信。

要求：不超过 80 字，语气礼貌，说明延期原因和新的交付时间。'''

说明("""【第一版】的提问：
  「帮我写一条给客户的产品延期通知短信。要求：不超过 80 字，语气礼貌，
  说明延期原因和新的交付时间。」""")
try:
    第一版 = 问模型(第一版要求, 温度=0.7, 最长回答=200)
    说明('   ' + 第一版.strip()[:200])
except Exception as e:
    说明('   ❌ ' + 友好报错(e))

说明('')
说明("""【改法 3：只说"不对"】提问是在第一版基础上追加一句：「不对，重来」。""")
try:
    回答 = 问模型(第一版要求 + '\\n\\n不对，重来', 温度=0.7, 最长回答=200)
    说明('   ' + 回答.strip()[:200])
except Exception as e:
    说明('   ❌ ' + 友好报错(e))

说明('')
说明("""【改法 1：指出具体问题 + 说清要什么】提问是第一版基础上追加：
  「上一版有两个问题：1. 没写清楚延期到哪一天，日期是必需要素；
  2. 语气太生硬。请重写，务必包含具体日期（假设延期到 3 月 15 日），
  语气像老朋友沟通。」""")
try:
    回答 = 问模型(第一版要求 + '''
\\n\\n上一版有两个问题：
1. 没有写清楚延期到哪一天，日期是必需要素
2. 语气太生硬，像通知不像沟通

请重写，务必包含具体日期（假设延期到 3 月 15 日），语气像老朋友沟通。''',
        温度=0.5, 最长回答=200)
    说明('   ' + 回答.strip()[:220])
except Exception as e:
    说明('   ❌ ' + 友好报错(e))

说明('')
说明('''👆 改法 1 明显更好。

【核心心法】
  AI 不理解"你不喜欢"，但它非常理解"把第 2 段改成……"。
  和 AI 沟通，要像跟一个新来的实习生交代任务——具体、明确、可检查。''')


