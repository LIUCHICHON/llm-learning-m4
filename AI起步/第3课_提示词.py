小节('实验 4：做一张你自己的提示词模板')

说明('''实战中，每次从零写提示词太慢。最好的做法是：沉淀成模板。

我给你一张通用模板（存在你的脑子里，或者存进备忘录）：''')

说明('''────────────────────────────────────────────
  通用提示词模板
────────────────────────────────────────────

  你是【角色/身份】。

  任务： 【要做什么，一句话说清】

  背景： 【给谁看、什么场景、有什么限制】

  输入材料：
  【粘贴原文/数据，没有就写"无"】

  输出要求：
  · 格式：【表格/列表/JSON/纯文本】
  · 长度：【多少字/几条】
  · 语言：【中文/英文】
  · 语气：【专业/口语/严肃】
  · 不要：【明确排除的内容，如"不要解释"、"不要客套"】

  示例（如有）：
  【贴一个你想要的输出样本】
────────────────────────────────────────────''')

说明('''【什么时候用哪个零件】
  · 一次性任务 → 随便拼，能用就行
  · 天天重复的任务 → 存成模板，每次填空
  · 要给别人用 → 写清"不要做什么"，比写清"要做什么"更重要''')


