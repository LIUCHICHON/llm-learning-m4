标题('第 3 课 · 怎样把话说得更准')

说明('''上一课你发现"问法"决定输出质量。这一课我们把它变成技术。

核心结论先给你：一个好提示词 = 6 个零件。
你只要把这 6 个格子填满，输出质量会有质的飞跃。''')


# ===========================================================================
# 零件拆解
# ===========================================================================
小节('先看看：一个好提示词的 6 个零件')

说明('''【零件 1：角色】你是谁
  "你是一位有 20 年经验的儿科医生"
  作用：决定用词风格、专业深度、关注点。

【零件 2：任务】要做什么
  "帮我写一封邮件"
  作用：最核心的一句，别绕弯子。

【零件 3：背景】给谁看、在什么场景
  "收件人是我的客户，语气要礼貌但不能生硬"
  作用：决定分寸。

【零件 4：输入材料】要处理的具体内容
  "以下是会议记录：..."
  作用：有原文就贴原文，别让模型猜。

【零件 5：输出要求】格式、长度、语言
  "用 3 个要点回答，每个不超过 30 字，用中文"
  作用：这条最容易被忽略，也最容易决定"能不能直接用"。

【零件 6：示例】给它看个样儿（可选但强烈推荐）
  "像这样：输入 xxx → 输出 yyy"
  作用：比任何形容词都有效。''')


# ===========================================================================
# 实验 1：对比 —— 没零件 vs 有零件
# ===========================================================================
小节('实验 1：同一个任务，两种问法')

任务 = '总结这篇文章'

没有零件的提示词 = 任务 + '''
这篇文章讲的是作者出差时遇到的一次软件故障。他一开始以为是网络问题，
排查了很久，最后发现是配置文件里一个字符写错了。文章最后建议，
遇到异常时应该先检查最简单的原因，而不是一上来就上重工具。'''

有零件的提示词 = '''你是一位技术团队的知识管理专员。

任务：把下面这段文字总结成 3 个要点。

背景：这些要点要放进团队周报，读者是不了解细节的新同事。

输出要求：
  · 严格 3 条，每条一行
  · 每条不超过 30 个汉字
  · 用中文，开头用「·」符号
  · 不要出现原文里的技术术语，用大白话

输入材料：
''' + 没有零件的提示词.split('\n', 3)[3]

说明("""【问法 A】只有一句话 + 一堆原文
  我实际问它的话：「总结这篇文章」+ 一段软件故障的原文。
  也就是说，只给一句命令，然后把材料原样丢给它。""")
try:
    回答A = 问模型(没有零件的提示词, 温度=0.5, 最长回答=300)
    说明('【回答 A】')
    for 行 in 回答A.strip().split('\n')[:10]:
        说明('   ' + 行)
except Exception as e:
    说明('   ❌ ' + 友好报错(e))

说明('')
说明("""【问法 B】填满 6 个零件
  我实际问它的话：
  「你是一位技术团队的知识管理专员。任务：把下面这段文字总结成 3 个要点。
  背景：要点要放进团队周报，读者是不了解细节的新同事。
  输出要求：严格 3 条、每条一行、每条不超过 30 个汉字、中文、开头用「·」、
  不要出现技术术语用大白话。」+ 同一段原文。""")
try:
    回答B = 问模型(有零件的提示词, 温度=0.5, 最长回答=300)
    说明('【回答 B】')
    for 行 in 回答B.strip().split('\n')[:10]:
        说明('   ' + 行)
except Exception as e:
    说明('   ❌ ' + 友好报错(e))

说明('')
说明('''👆 同样一台电脑、同一段材料：
  回答 A 是一段话，你得自己再加工一遍才能用；
  回答 B 直接就是能贴进周报的样子。

【记住这个道理】
  你花的每一分钟在写清楚需求，省下的都是后面十次的返工。''')


# ===========================================================================
# 实验 2：格式控制
# ===========================================================================
小节('实验 2：怎么让输出格式绝对稳定')

说明('''上一课你看到模型很听话。但真实情况是：**同样的问题，多跑几次格式可能不一样。**

这在要批量处理数据时是灾难。我们要学会把它"钉死"。''')

不稳的提示词 = '列出 5 个适合送长辈的礼物'

稳的提示词 = '''列出 5 个适合送长辈的礼物。

【硬性格式要求，必须严格遵守】
1. 每一行的格式必须是：序号.礼物名称——一句话理由
2. 序号用中文数字：一、二、三、四、五
3. 理由不超过 20 个汉字
4. 只输出这 5 行，不要有任何其他文字
5. 不要输出标题、不要输出解释、不要用markdown代码块

现在开始，直接输出 5 行：'''

说明("""【不加格式约束】的提问：「列出 5 个适合送长辈的礼物」。跑 2 次：""")
for i in range(2):
    try:
        回答 = 问模型(不稳的提示词, 温度=0.7, 最长回答=250)
        首行 = 回答.strip().split('\n')[0][:70]
        说明(f'   第{i+1}次首行: {首行}')
    except Exception as e:
        说明(f'   ❌ ' + 友好报错(e))

说明('')
说明("""【加格式约束】的提问：还是「列出 5 个适合送长辈的礼物」，但补上硬性要求——
  每行格式「序号.礼物名称——一句话理由」、序号用中文数字、理由不超过 20 字、
  只输出这 5 行、不要标题和解释。跑 2 次：""")
for i in range(2):
    try:
        回答 = 问模型(稳的提示词, 温度=0.3, 最长回答=250)
        说明(f'   第{i+1}次完整输出：')
        for 行 in 回答.strip().split('\n')[:7]:
            说明('      ' + 行)
        说明('')
    except Exception as e:
        说明(f'   ❌ ' + 友好报错(e))

说明('''👆 差别很明显：不加约束时模型可能写标题、加解释、用英文；
  加了"硬性格式要求"之后，每次输出都是可以直接入库的干净数据。

【三条让格式变稳的技巧】
  1. 说"必须"、"严格"、"只输出"，这些词本身就在加强语气
  2. 给出正例（一个你想要的输出样本），比描述更有效
  3. 温度调低到 0.2~0.3''')


