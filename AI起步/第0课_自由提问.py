# -*- coding: utf-8 -*-
'''
自由提问实验 · 你自己打字问 AI

这个脚本让你亲手问本机的大模型。
它会：
  1. 让你输入任何问题
  2. 显示模型的回答
  3. 让你调节"温度"再问一次，对比差别

用法：直接运行这个文件，或者在上课.sh 里选 8
'''

from AI工具箱 import 标题, 小节, 说明, 问模型, 检查引擎, 友好报错

标题('自由提问 · 你自己打字问 AI')

if not 检查引擎():
    说明('❌ AI 引擎没有运行。请另开一个终端窗口输入 ollama serve 然后回车。')
    raise SystemExit(1)

说明('✅ AI 引擎已就绪。下面你可以随便问它问题。')


def 问一个问题(问题, 温度):
    """问一个问题并显示回答。"""
    print()
    print(f'  你的问题: {问题}')
    print(f'  温度设置: {温度}')
    print('  ' + '─' * 56)
    try:
        回答 = 问模型(问题, 温度=温度, 最长回答=400)
        # 逐行缩进显示
        for 行 in 回答.strip().split('\n'):
            print(f'  AI: {行}')
    except Exception as e:
        print(f'  ❌ 出错了: {友好报错(e)}')


# ===========================================================================
# 第一次：让你自由输入问题
# ===========================================================================
小节('第 1 次提问 · 温度 0.7（正常发挥）')

说明('''现在轮到你了。
在下面输入你的问题，然后按回车（输入英文问号 ? 或直接回车跳过，用默认问题）。

试试问这些：
  · 中国最南边的省份是哪里？
  · 用一句话解释什么是"通货膨胀"
  · 帮我起一个奶茶店的名字
  · 为什么天空是蓝色的？
''')

try:
    你的问题 = input('  你的问题> ').strip()
except EOFError:
    你的问题 = ''

if not 你的问题:
    你的问题 = '中国最南边的省份是哪里？'
    说明(f'  （没输入，用默认问题：{你的问题}）')

问一个问题(你的问题, 0.7)


# ===========================================================================
# 第二次：同一个问题，高温
# ===========================================================================
小节('第 2 次提问 · 同样的问题，温度调到 1.2')

说明('''现在把温度调高到 1.2（更随机），再问一次一模一样的问题。
看看两次回答有什么不同。

温度是"发挥空间"：
  · 温度低（0.1~0.3）→ 每次都选最稳的那个词，回答几乎一样
  · 温度高（0.9~1.2）→ 冷门词也有机会被选，回答差异大

注意：不是每次高温都一定差。有些问题（比如创意写作）高温反而更好。
''')

问一个问题(你的问题, 1.2)


# ===========================================================================
# 第三次：对比总结
# ===========================================================================
小节('对比一下')

说明('''刚才你亲眼看到：
  · 同一个问题，两次回答不完全一样
  · 高温时模型更"敢发挥"，低温时更"保守"

【为什么？】
  模型不是从答案库里查，而是每生成一个词都按概率抽。
  温度就是调这个概率分布的形状。

【现在试个更明显的】
  我们用一个"没有唯一答案"的问题，重复问 4 次，
  每次温度都是 1.0。你会看到 4 个不同的版本。

  想自己试？按回车继续，或输入 q 跳过:''')

创意问题 = '给一个卖潮汕牛肉丸的店起个店名，要有故事感'

try:
    继续 = input('  按回车继续 > ').strip().lower()
except EOFError:
    继续 = ''

if 继续 != 'q':
    print()
    for i in range(4):
        try:
            回答 = 问模型(创意问题, 温度=1.0, 最长回答=60)
            首行 = 回答.strip().split('\n')[0]
            print(f'  第{i+1}次: {首行[:70]}')
        except Exception as e:
            print(f'  ❌ {友好报错(e)}')
    print()
    说明('👆 4 个不同的店名。这就是大模型的"生成"能力。')
    说明('   而搜索引擎做不到这件事——它只能给你找到的网页。')


标题('玩够了？回到课程')

说明('''  上课命令：
    bash AI起步/上课.sh

  输入 1 继续第 1 课，2~7 进入后面的课。

  【一句话总结】
  温度 = 模型的发挥空间。低=保守稳定，高=多样奔放。
  写代码和算数用低温度，聊天和创意用中温度。
''')
