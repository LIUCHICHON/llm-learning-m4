说明('【第 4 步：装上 LoRA 补丁（最核心的一步）】')
说明('''
   lora_config = LoraConfig(
       r=8,                        # 补丁的"秩"，可调，8 足够
       lora_alpha=16,              # 缩放系数，一般是 r 的 2 倍
       lora_dropout=0.05,          # 随机丢弃一点，防过拟合
       target_modules=["q_proj", "v_proj"],   # 补丁装在哪两层
       task_type="CAUSAL_LM",      # 因果语言模型任务
   )
   model = get_peft_model(model, lora_config)

   【什么是"秩 r"】
     想象模型里有一层很大的矩阵（比如 2048×2048）。
     LoRA 的做法是：不改它，而在旁边加两个瘦长的小矩阵（2048×8 和 8×2048），
     训练时只调这两个小矩阵。
     效果接近全参微调，但可训练参数少了几百倍。

   【q_proj / v_proj 是什么】
     Transformer 里的"注意力"机制有两组投影矩阵（query、value）。
     在这两处加补丁，是业界验证过效果最好、最省资源的选择。

   【训练后你会看到】
     trainable params: 540,672 || all params: 494,573,440 || trainable%: 0.1093
     ↑ 意思是：5.4 万个参数要训练，占全部的 0.1%
''')

