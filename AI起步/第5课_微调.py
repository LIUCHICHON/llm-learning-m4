说明('''
   def collator(feats):
       b = tok([f["text"] for f in feats], return_tensors="pt", padding=True,
               truncation=True, max_length=256)
       labels = b["input_ids"].clone()
       for i, f in enumerate(feats):
           提示 = f"### 指令:\n{f['问']}\n### 回答:\n"
           提示长度 = len(tok(提示, add_special_tokens=False)['input_ids'])
           真实长度 = len(tok(f['text'], add_special_tokens=False)['input_ids'])
           labels[i, :提示长度] = -100
           labels[i, 真实长度:] = -100
       b["labels"] = labels
       return b

   【逐行解释】
   tok(...)          —— 分词，并把这一批文本转成模型能吃的数字
   padding=True      —— 每条长度不一样，短的要补齐（补的叫 pad）
   truncation=True   —— 太长的砍掉，max_length=256 最多留 256 个 token
   labels = ...      —— 告诉模型"哪些位置是真正要学的"
   【关键改进】旧版只写一行 labels[labels==pad]==-100，有两个坑：
     ① pad_token 和 eos_token 是同一个，会把答案末尾的结束标记一并抹掉；
     ② "### 指令+问题"也参与了学习，模型分心去背问题。
     新版：问题部分设 -100（不用学），结束标记保留（学会停），只学答案。
   这就是"collator"：把一批原始样本整理成一批模型输入的函数。

   【以哪一段为准】本部分只是逐行讲解原理。真正要敲的代码在第 4 部分
   "开跑（步骤和结果，自己动手）"，两处已经同步为新版，照第 4 部分贴即可。
''')

