说明('''
   原始数据是"问/答"两个字段，但模型需要的是一段纯文本。
   所以要做一次"格式化"：

   问：潮汕牛肉丸是什么？
   答：潮汕牛肉丸是汕头特产……

   ↓ 格式化 ↓

   ### 指令:
   潮汕牛肉丸是什么？
   ### 回答:
   潮汕牛肉丸是汕头特产……<|endoftext|>

   这个 ### 标记叫"聊天模板"（chat template），
   是模型训练时约定的格式。必须和模型原本的格式一致，否则效果打折。

   【关键】答案末尾那个 <|endoftext|> 是"结束标记"（tok.eos_token），
   教模型"说到这里就停"。代码里写成 {样本['答']}{tok.eos_token}。
   少了它，模型学不会停，答完就继续往下编——这是上次串味的根因之一。
''')

