from AI工具箱 import 标题, 小节, 说明, 问模型, 逐字显示, 友好报错

标题('第 2 课 · 第一次让电脑回答你')

说明('''欢迎。这一课我们会真正跟模型对话。

先讲清楚一件事：你在浏览器里用的 ChatGPT、通义千问、Kimi，
背后都是同一套原理——把你的话发给一个模型，把它的回答显示出来。

区别只在于：
  · 网页版：模型跑在别人的服务器上（要联网，要花钱或用额度）
  · 今天这课：模型跑在你自己电脑上（不花钱，不联网，不外传）

你自己跑模型的好处：
  1. 隐私——你写的任何东西都不会离开这台电脑
  2. 免费——没有 token 费用，随便折腾
  3. 可控——能调温度、能换模型、能微调''')


# ===========================================================================
# 实验 1：最朴素的问法
# ===========================================================================
小节('实验 1：先问一个最简单的问题')

说明('''我们先问一个很平常的问题，然后逐个改进它。
你会亲眼看到"问法"对回答质量的影响有多大。''')

朴素的问法 = '写一份旅行计划'

说明("""【问法 1】我实际问它的话：「写一份旅行计划」。就这一句，什么细节都没给。""")

try:
    回答 = 问模型(朴素的问法, 温度=0.7, 最长回答=200)
    说明('【问法 1】' + 朴素的问法)
    说明('【回答】')
    for 行 in 回答.strip().split('\n')[:8]:
        说明('   ' + 行)
    说明('   ...（后面还有）')
except Exception as e:
    说明('❌ 出错了：' + 友好报错(e))

说明('')
说明('''👆 你发现问题了吗？回答是"正确的"，但完全没法用。

因为你没说清楚：去哪儿？几天？什么预算？什么风格？

这就是使用 AI 的第一课：**它不会猜你的心思，你必须把话说清楚。**''')


# ===========================================================================
# 实验 2：加上关键信息
# ===========================================================================
小节('实验 2：把话说清楚')

说明('''我们把"去哪儿、几天、什么风格"都补上，再问一次。

这里用到一个很重要的概念：

【系统提示 / 角色设定】
  你可以先告诉模型"你是谁、要干什么"，再问问题。
  相当于给它派了个岗。同一段内容，用不同的岗位说出来味道完全不同。''')

好的问法 = '''帮我规划一个旅行计划。

目的地：汕头
天数：3 天
同行：带 6 岁小孩和 70 岁老人
预算：3000 元以内
要求：不要太累，每天最多安排 2 个景点'''

说明("""【问法 2】的完整提问（补齐 目的地 / 天数 / 同行人 / 预算 / 要求）：
  帮我规划一个旅行计划。目的地：汕头；天数：3 天；
  同行：带 6 岁小孩和 70 岁老人；预算：3000 元以内；
  要求：不要太累，每天最多安排 2 个景点。""")

try:
    回答 = 问模型(好的问法, 温度=0.7, 最长回答=400)
    说明('【问法 2】的回答：')
    说明('【回答】')
    for 行 in 回答.strip().split('\n')[:12]:
        说明('   ' + 行)
except Exception as e:
    说明('❌ 出错了：' + 友好报错(e))

说明('')
说明('👆 这次的回答立刻能用了。**同样的模型，问法差一截，输出差十倍。**')


# ===========================================================================
# 实验 3：给模型派个岗（系统提示）
# ===========================================================================
小节('实验 3：给模型派个岗')

说明('''同一个问题，让模型扮演不同角色，答案完全不同。

【为什么这个技巧重要】
  · 让它当"导游"，它会讲景点故事
  · 让它当"行程规划师"，它会给出紧凑的时间表
  · 让它当"熊孩子"，它会更活泼

在编程里同样有用——这是后面第 5 课微调的基础概念之一。''')

问题 = '介绍一下汕头的美食'

说明("""【这一轮的共同问题】介绍一下汕头的美食。
下面让它分别扮演 美食博主 / 营养师 / 外省游客 三个角色来回答。""")

for 角色, 设定 in [
    ('美食博主', '你是一位汕头本地的美食博主，说话接地气，会推荐私藏小店。'),
    ('营养师', '你是一位营养师，回答会标注热量和营养成分。'),
    ('外省游客', '你是一位第一次来汕头的外省游客，说话客气，常问路。'),
]:
    try:
        回答 = 问模型(问题, 温度=0.7, 最长回答=180, 系统提示=设定)
        说明(f'【角色：{角色}】')
        说明('   ' + 回答.strip().replace('\n', '\n   ')[:280])
        说明('')
    except Exception as e:
        说明(f'❌ {角色} 出错：' + 友好报错(e))

说明('👆 同一台电脑、同一套模型，只因为"岗位"不同，语气和内容就完全不同。')


# ===========================================================================
# 实验 4：三个立刻能用的技巧
# ===========================================================================
小节('实验 4：三个立刻能用的提问技巧')

说明('''【技巧 1：让它先想再答（思维链）】

不加这句话时，模型直接给答案，你不知道它怎么想的；
加上之后，它会先拆解问题再回答，准确率明显提高。

适合：数学题、推理题、复杂分析、代码调试。''')

难题 = '一个笼子里有鸡和兔，共 35 个头，94 只脚，鸡兔各几只？'

说明("""【这一轮的提问】一个笼子里有鸡和兔，共 35 个头，94 只脚，鸡兔各几只？
我们问两次：第一次不加思维链，第二次加「请先列出方程，一步一步求解」。""")

说明('不加思维链：')
try:
    回答 = 问模型(难题, 温度=0.3, 最长回答=150)
    说明('   ' + 回答.strip().replace('\n', '\n   ')[:220])
except Exception as e:
    说明('   ❌ ' + 友好报错(e))

说明('')
说明('加上思维链：')
try:
    回答 = 问模型(难题 + '\n\n请先列出方程，一步一步求解，最后给出答案。',
                  温度=0.3, 最长回答=300)
    说明('   ' + 回答.strip().replace('\n', '\n   ')[:420])
except Exception as e:
    说明('   ❌ ' + 友好报错(e))

说明('')
说明('''【技巧 2：给它一个例子（少样本）】

想让模型按某种格式输出时，与其描述格式，不如直接给一个例子。''')

格式题 = '把下面三本书整理成一行，格式是「书名-作者-年份」，只输出整理结果，不要解释：\\n1. 三体 / 刘慈欣 / 2008\\n2. 活着 / 余华 / 1993\\n3. 百年孤独 / 加西亚·马尔克斯 / 1967'

说明("""【这一轮的提问】把三本书整理成一行「书名-作者-年份」，只输出结果、不解释：
  1. 三体 / 刘慈欣 / 2008
  2. 活着 / 余华 / 1993
  3. 百年孤独 / 加西亚·马尔克斯 / 1967""")

try:
    回答 = 问模型(格式题, 温度=0.2, 最长回答=150)
    说明('   ' + 回答.strip()[:250])
except Exception as e:
    说明('   ❌ ' + 友好报错(e))

说明('')
说明('''【技巧 3：一次问清楚，别来回挤牙膏】

很多人抱怨 AI 不好用，是因为第 1 轮问得太模糊，
然后 5 轮来回纠错。更好的做法：第 1 轮就把信息给全。''')


# ===========================================================================
# 实验 5：怎么让回答一个词一个字出现
# ===========================================================================
小节('实验 5：看它是怎么一个字一个字想出来的')

说明('''你见过的 AI 对话都是"逐字显示"的（一个词一个词冒出来）。
那是因为模型本来就是这么生成的——它每次只往前走一小步。

我们直接看这个过程。''')

try:
    逐字显示('用一句话解释什么是"微调"', 温度=0.6)
except Exception as e:
    说明('❌ ' + 友好报错(e))

说明('''👆 这就是"逐字输出"。你可以理解成：
模型在玩一个接龙游戏，每个字都接在前面所有字的后面。
接龙接得多了，自然就成了通顺的一段话。''')


